// Writes what the build needs from the content model: typed data for Angular, sitemap, RSS feeds and
// the Azure Static Web Apps config with a rewrite for every prerendered page.
import { allUrls, visibleAreas } from './load.mjs';
import { FEED, ORIGIN } from './schema.mjs';

const HEADER = '// Generated by scripts/build-content.mjs from content/**/*.md – do not edit, change the markdown instead.\n';

/** Key of a text body: 'article:cs:<slug>', 'study:en:<slug>', 'page:cs:<page key>'. */
export const bodyKey = (kind, lang, id) => `${kind}:${lang}:${id}`;
const bodyFile = (key) => key.replace(/:/g, '-');

/**
 * The generated TypeScript: content.generated.ts with everything lists and meta tags need, and one
 * module per text body in bodies/. The bodies are loaded with import() only for the page that shows
 * them, so the main bundle does not grow with every article (code splitting).
 * @returns {Record<string, string>} path relative to src/app/content → file text
 */
export function generatedTs(model) {
  const json = (v) => JSON.stringify(v, null, 2);
  const files = {};
  const bodies = [];
  const strip = (kind, lang, id, item) => {
    const { blocks, ...meta } = item;
    const key = bodyKey(kind, lang, id);
    bodies.push(key);
    files[`bodies/${bodyFile(key)}.ts`] = `${HEADER}import type { Block } from '../../i18n/types';\n\nexport const blocks: Block[] = ${json(blocks)};\n`;
    return meta;
  };
  const byLang = (list, kind) =>
    Object.fromEntries(Object.entries(list).map(([lang, items]) => [lang, items.map((it) => strip(kind, lang, it.slug, it))]));
  const articles = byLang(model.articles, 'article');
  const studies = byLang(model.studies, 'study');
  const pages = Object.fromEntries(
    Object.entries(model.pages).map(([key, langs]) => [key, Object.fromEntries(Object.entries(langs).map(([lang, p]) => [lang, strip('page', lang, key, p)]))]),
  );
  const loaders = bodies.map((k) => `  '${k}': () => import('./bodies/${bodyFile(k)}').then((m) => m.blocks),`).join('\n');

  files['content.generated.ts'] = `${HEADER}import type { Area, Article, Block, CaseStudy, ContentPage, Lang, PageKey } from '../i18n/types';

/** True when the build includes drafts (stav: koncept) – npm start and npm run build:drafts. */
export const DRAFTS_INCLUDED: boolean = ${model.includeDrafts};

/** Article areas in menu order, only those with at least one article. */
export const AREAS: Area[] = ${json(visibleAreas(model))};

/** Articles, newest first (without the text; see BODIES). */
export const ARTICLES: Record<Lang, Article[]> = ${json(articles)};

/** Case studies, newest first (without the text; see BODIES). */
export const STUDIES: Record<Lang, CaseStudy[]> = ${json(studies)};

/** Pages written in markdown (content/stranky), by page key (without the text; see BODIES). */
export const PAGES: Partial<Record<PageKey, Record<Lang, ContentPage>>> = ${json(pages)};

/** Text of each article, study and page, loaded only when its page is opened. */
export const BODIES: Record<string, () => Promise<Block[]>> = {
${loaders}
};
`;
  return files;
}

const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function sitemapXml(model, paths) {
  const urls = allUrls(model, paths);
  const body = urls
    .map((u) => {
      const lines = [`    <loc>${xml(ORIGIN + u.path)}</loc>`];
      if (u.lastmod) lines.push(`    <lastmod>${u.lastmod}</lastmod>`);
      lines.push(
        `    <xhtml:link rel="alternate" hreflang="cs" href="${xml(ORIGIN + u.alt.cs)}"/>`,
        `    <xhtml:link rel="alternate" hreflang="en" href="${xml(ORIGIN + u.alt.en)}"/>`,
        `    <xhtml:link rel="alternate" hreflang="x-default" href="${xml(ORIGIN + u.alt.cs)}"/>`,
      );
      return `  <url>\n${lines.join('\n')}\n  </url>`;
    })
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-content.mjs – do not edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${body}
</urlset>
`;
}

const rfc822 = (date) => new Date(`${date}T00:00:00Z`).toUTCString();

/** RSS 2.0 feed of the articles in one language. */
export function feedXml(model, paths, lang) {
  const prefix = lang === 'en' ? '/en/' : '/';
  const listUrl = `${ORIGIN}${prefix}${paths[lang].articles}`;
  const items = model.articles[lang]
    .map((a) => {
      const link = `${listUrl}/${a.slug}`;
      const area = model.areas.find((x) => x.id === a.area);
      return `    <item>
      <title>${xml(a.title)}</title>
      <link>${xml(link)}</link>
      <guid isPermaLink="true">${xml(link)}</guid>
      <pubDate>${rfc822(a.published)}</pubDate>
      <description>${xml(a.perex)}</description>${area ? `\n      <category>${xml(area.name[lang])}</category>` : ''}
    </item>`;
    })
    .join('\n');
  const newest = model.articles[lang].map((a) => a.updated ?? a.published).sort().at(-1);
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${xml(FEED[lang].title)}</title>
    <link>${xml(listUrl)}</link>
    <description>${xml(FEED[lang].description)}</description>
    <language>${lang}</language>${newest ? `\n    <lastBuildDate>${rfc822(newest)}</lastBuildDate>` : ''}
    <atom:link href="${xml(`${listUrl}/feed.xml`)}" rel="self" type="application/rss+xml"/>
${items}
  </channel>
</rss>
`;
}

/**
 * staticwebapp.config.json = staticwebapp.config.base.json + a rewrite "/path" → "/path/index.html"
 * for every prerendered page (without it Static Web Apps would serve the client-side fallback).
 */
export function staticWebAppConfig(base, model, paths) {
  const rewrites = allUrls(model, paths)
    .filter((u) => u.path !== '/')
    .map((u) => ({ route: u.path, rewrite: `${u.path}/index.html` }));
  return `${JSON.stringify({ ...base, routes: [...rewrites, ...(base.routes ?? [])] }, null, 2)}\n`;
}
